  page.get_by_label('Business name',exact=True).fill('Example Venture')
  page.get_by_label('One-line pitch',exact=True).fill('Useful software for independent businesses')
  page.get_by_label('Problem and solution',exact=True).fill('Small businesses need clearer tools. This is a fictional proposal for testing.')
  page.get_by_label('Progress so far',exact=True).fill('Sample idea-stage research.')
