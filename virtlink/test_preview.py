"""Browser regression checks for the isolated concept preview."""
import functools, http.server, pathlib, threading, unittest
from playwright.sync_api import sync_playwright
ROOT=pathlib.Path(__file__).resolve().parent
class PreviewTests(unittest.TestCase):
 @classmethod
 def setUpClass(cls):
  cls.http=http.server.ThreadingHTTPServer(('127.0.0.1',0),functools.partial(http.server.SimpleHTTPRequestHandler,directory=str(ROOT/'dist')))
  threading.Thread(target=cls.http.serve_forever,daemon=True).start()
  cls.pw=sync_playwright().start();cls.browser=cls.pw.chromium.launch()
  cls.url=f'http://127.0.0.1:{cls.http.server_port}/'
 @classmethod
 def tearDownClass(cls):
  cls.browser.close();cls.pw.stop();cls.http.shutdown();cls.http.server_close()
 def test_account_gate(self):
  page=self.browser.new_page(viewport={'width':390,'height':844});errors=[];auth_requests=[]
  page.on('pageerror',lambda e:errors.append(str(e)))
  page.route('https://challenges.cloudflare.com/**',lambda route:route.fulfill(content_type='text/javascript',body='window.turnstile={render:()=>1,reset:()=>{}};'))
  page.route('https://hnoqhdqnvvndyipcoudi.supabase.co/**',lambda route:(auth_requests.append(route.request.url),route.abort()))
  page.goto(self.url+'accounts.html')
  page.get_by_text('Sign in with your existing test account.',exact=True).wait_for()
  self.assertFalse(page.locator('#profilePanel').is_visible())
  self.assertFalse(page.locator('#mfaPanel').is_visible())
  page.get_by_label('Email (required)',exact=True).fill('test@example.invalid')
  page.get_by_label('Password (required)',exact=True).fill('NotARealPassword')
  page.get_by_role('button',name='Sign in securely',exact=True).click()
  page.get_by_text('Complete the human check first.',exact=True).wait_for()
  self.assertEqual(page.get_by_label('Password (required)',exact=True).input_value(),'')
  self.assertEqual(auth_requests,[])
  self.assertFalse(page.evaluate('document.documentElement.scrollWidth > innerWidth'))
  self.assertEqual(errors,[])
  page.screenshot(path=str(ROOT/'accounts-mobile-preview.png'),full_page=True)
  page.close()
 def test_connected_profile(self):
  page=self.browser.new_page();errors=[]
  page.on('pageerror',lambda e:errors.append(str(e)))
  # Exercise main-page identity rendering independently of real credentials.
  page.route('**/account-main.js',lambda route:route.fulfill(content_type='text/javascript',body=''))
  page.goto(self.url+'#profile')
  row={'display_name':'Account <Example>','headline':'Engineer','profession':'Technology','location':'Example city','skills':'Coding, Design','looking_for':'Collaborators','bio':'Saved biography'}
  page.evaluate('(row)=>window.dispatchEvent(new CustomEvent("virtlink-account",{detail:row}))',row)
  self.assertTrue(page.get_by_role('heading',name='Account <Example>',exact=True).is_visible())
  self.assertTrue(page.get_by_text('Saved biography',exact=True).is_visible())
  self.assertEqual(page.locator('.loginButton').inner_text(),'Sign out')
  page.goto(self.url+'#feed')
  page.get_by_role('textbox',name='Write a post').fill('Test preview post')
  page.get_by_role('button',name='Post',exact=True).click()
  self.assertNotIn('Account <Example>',page.evaluate('sessionStorage.getItem("virtlink-preview-v1")'))
  page.evaluate('window.dispatchEvent(new CustomEvent("virtlink-account",{detail:null}))')
  self.assertEqual(page.locator('.loginButton').inner_text(),'Login')
  self.assertNotIn('Account <Example>',page.locator('#app').inner_text())
  self.assertEqual(errors,[]);page.close()
 def test_preview(self):
  page=self.browser.new_page(viewport={'width':1440,'height':1000});errors=[]
  page.on('pageerror',lambda e:errors.append(str(e)))
  page.goto(self.url)
  page.locator('.heroCity').wait_for()
  self.assertTrue(page.locator('.heroCity').evaluate('(i)=>i.complete && i.naturalWidth>0'))
  page.screenshot(path=str(ROOT/'welcome-preview.png'),full_page=True)
  page.get_by_role('button',name='Sign Up',exact=True).click()
  self.assertTrue(page.get_by_text('Public accounts are not open yet.',exact=False).is_visible())
  self.assertEqual(page.locator('input[type=password]').count(),0)
  page.get_by_role('button',name='Close dialog').click()
  for route in ['feed','network','jobs','communities','events','marketplace','messages','profile','saved','world','security','investors','terms','privacy','investor-policy','community-policy','menu']:
   page.goto(self.url+'#'+route)
   page.locator('main h1').wait_for()
   self.assertFalse(page.evaluate('document.documentElement.scrollWidth > innerWidth'),route)
   if route in ['feed','world','profile','jobs','messages']:
    page.screenshot(path=str(ROOT/(route+'-preview.png')),full_page=True)
  page.goto(self.url+'#feed')
  page.get_by_role('textbox',name='Write a post').fill('<img src=x onerror="alert(1)"> Preview post')
  page.get_by_role('button',name='Post',exact=True).click()
  self.assertTrue(page.get_by_text('<img src=x onerror="alert(1)"> Preview post',exact=True).is_visible())
  self.assertEqual(page.locator('.bodyText img').count(),0)
  page.locator('[data-action="save"]').first.click()
  page.goto(self.url+'#saved');self.assertEqual(page.locator('.post').count(),1)
  page.goto(self.url+'#network')
